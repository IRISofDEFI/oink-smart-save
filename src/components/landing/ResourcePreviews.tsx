// Real commits per day from this repo, generated by scripts/commit-activity.mjs.
const weeks = activity.weeks as (number | null)[][];
// Column-major (week by week) so the fill-in stagger sweeps left to right.
const days = weeks.flat();
const filled = days.flatMap((n, i) => (n ? [i] : []));

function levelClass(n: number | null) {
  if (n === null) return "invisible"; // after the latest commit
  if (n === 0) return "bg-ink/[0.07]";
  if (n === 1) return "bg-brand-dark/40";
  if (n <= 3) return "bg-brand-dark/70";
  if (n <= 8) return "bg-brand-dark/90";
  return "bg-brand-dark";
}

/**
 * A few filled squares softly brighten and fade back every ~1.6s, like live
 * activity. Client-only (random), paused off-screen and under reduced motion.
 */
function useTwinkle(active: boolean) {
  const [lit, setLit] = useState<number[]>([]);
  useEffect(() => {
    if (!active || filled.length === 0) return;
    let clear: ReturnType<typeof setTimeout> | undefined;
    const tick = () => {
      const picks = new Set<number>();
      while (picks.size < Math.min(2, filled.length)) {
        picks.add(filled[Math.floor(Math.random() * filled.length)]);
      }
      setLit([...picks]);
      clear = setTimeout(() => setLit([]), 900);
    };
    const id = setInterval(tick, 1600);
    return () => {
      clearInterval(id);
      clearTimeout(clear);
      setLit([]);
    };
  }, [active]);
  return lit;
}

/**
 * GitHub: this repo's real commit activity (columns = weeks, rows = Sun–Sat,
 * most recent on the right), filling in with a quick stagger, over a real
 * call from contracts/OinkSafe.sol.
 */
export function GitHubPreview() {
  const ref = useRef<HTMLDivElement>(null);
  const inView = useInView(ref);
  const reduce = useReducedMotion();
  const lit = useTwinkle(inView && !reduce);

  return (
    <div ref={ref} aria-hidden="true" className="flex w-[80%] flex-col items-center gap-4 sm:gap-5">
      <Stagger
        stagger={0.004}
        className="grid w-full grid-flow-col grid-rows-7 gap-[3px] sm:gap-1"
        style={{ gridTemplateColumns: `repeat(${weeks.length}, minmax(0, 1fr))` }}
      >
        {days.map((n, i) => (
          <StaggerItem key={i} y={0} className={`relative aspect-square rounded-[3px] ${levelClass(n)}`}>
            {n ? (
              <span
                className={`absolute inset-0 rounded-[3px] bg-white transition-[opacity,transform] duration-700 ease-in-out ${
                  lit.includes(i) ? "scale-110 opacity-60" : "scale-100 opacity-0"
                }`}
              />
            ) : null}
          </StaggerItem>
        ))}
      </Stagger>
      <code className="max-w-full truncate rounded-full bg-ink px-4 py-2 font-mono text-xs text-brand-light sm:text-[13px]">
        OinkSafe.lock(amount, durationDays)
      </code>
    </div>
  );
}
