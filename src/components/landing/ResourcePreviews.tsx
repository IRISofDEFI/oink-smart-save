import { Stagger, StaggerItem } from "./motion";

/**
 * Mini previews of each resource's destination, shown in the Resources card
 * image areas. The whitepaper page and activity grid are decorative (the card
 * title names the link); the X screenshot carries alt text. Hover effects key
 * off the card link's `group` class, are transform-only, and switch off under
 * reduced motion.
 */

const lift =
  "transition-transform duration-500 ease-out motion-reduce:transition-none motion-reduce:transform-none";

